            "        t_peak_rel = int(np.argmax(np.abs(t_region)))\n",
            "        m_T = t_start + t_peak_rel\n",
            "        t_amp_adc = float(signal[m_T] - pr_base)\n",
            "        t_offset_ms = round((m_T - m_R) * (1000.0 / fs), 2)\n",
            "        t_polarity = 1 if t_amp_adc > 15.0 else (-1 if t_amp_adc < -15.0 else 0)\n",
            "        t_wave_valid = bool(120.0 <= t_offset_ms <= 450.0)\n",
            "        \n",
            "        # T-Wave End Search post T-peak\n",
            "        m_Tend = min(m_T + int(round(0.120 * fs)), n_samples - 1)\n",
            "        for k in range(m_T, min(m_T + int(round(0.150 * fs)), n_samples - 1)):\n",
            "            if abs(signal[k] - pr_base) <= max(0.05 * abs(t_amp_adc), 5.0):\n",
            "                m_Tend = k\n",
            "                break\n",
            "        qt_ms = round((m_Tend - m_Q) * (1000.0 / fs), 2)\n",
            "        qt_valid = bool(250.0 <= qt_ms <= 600.0)\n",
            "    else:\n",
            "        t_amp_adc = np.nan\n",
            "        t_offset_ms = np.nan\n",
            "        t_polarity = 0\n",
            "        t_wave_valid = False\n",
            "        qt_ms = np.nan\n",
            "        qt_valid = False\n",
            "        \n",
            "    return {\n",
            "        \"pr_baseline_adc\": round(pr_base, 3),\n",
            "        \"j_offset_ms\": j_offset_ms,\n",
            "        \"j_point_valid\": j_point_valid,\n",
