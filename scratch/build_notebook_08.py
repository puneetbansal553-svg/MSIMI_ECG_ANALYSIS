            "        \"t_amp_adc\": round(t_amp_adc, 3) if np.isfinite(t_amp_adc) else np.nan,\n",
            "        \"t_offset_ms\": t_offset_ms if np.isfinite(t_offset_ms) else np.nan,\n",
            "        \"t_polarity\": t_polarity,\n",
            "        \"t_wave_valid\": t_wave_valid,\n",
            "        \"qt_ms\": qt_ms if np.isfinite(qt_ms) else np.nan,\n",
            "        \"qt_valid\": qt_valid,\n",
            "    }\n",
            "\n",
            "def compute_frontal_qrs_axis(lead_I: np.ndarray, lead_aVF: np.ndarray, fs: int) -> Tuple[float, bool]:\n",
            "    \"\"\"\n",
            "    Computes frontal plane QRS electrical axis (degrees) using Lead I and Lead aVF.\n",
            "    Returns (axis_degrees, axis_valid).\n",
            "    \"\"\"\n",
            "    m_R = 25 if fs == 100 else 125\n",
            "    w_pre = int(round(0.040 * fs))\n",
            "    w_post = int(round(0.060 * fs))\n",
            "    \n",
            "    net_I = float(np.sum(lead_I[m_R - w_pre : m_R + w_post + 1]))\n",
            "    net_aVF = float(np.sum(lead_aVF[m_R - w_pre : m_R + w_post + 1]))\n",
