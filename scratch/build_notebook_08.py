            "    if abs(net_I) < 1e-4 and abs(net_aVF) < 1e-4:\n",
            "        return np.nan, False\n",
            "        \n",
            "    axis_rad = math.atan2(net_aVF, net_I)\n",
            "    axis_deg = round(math.degrees(axis_rad), 2)\n",
            "    axis_valid = bool(-90.0 <= axis_deg <= 180.0)\n",
            "    return axis_deg, axis_valid\n",
            "\n",
